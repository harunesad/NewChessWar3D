        private void SetNoMatchState(PlayerMotionState playerState, string stateName)
        {
            if (playerState == null)
            {
                return;
            }

            playerState.DetectedMotionName = stateName;
            playerState.DetectedMotionConfidence = 0f;
            PopulateZeroScoresForTemplates(playerState);
            NotifyPlayerMotionScoresUpdated(playerState);
            NotifyPlayerMotionChangedIfNeeded(playerState);
        }

        private void PopulateZeroScoresForTemplates(PlayerMotionState playerState)
        {
            playerState.CurrentScores.Clear();
            playerState.MotionScores.Clear();

            if (templates.Count == 0)
            {
                return;
            }

            HashSet<string> addedMotionNames = new HashSet<string>(StringComparer.Ordinal);
            for (int i = 0; i < templates.Count; i++)
            {
                string motionName = ResolveTemplateDisplayName(templates[i].motionName);
                if (!addedMotionNames.Add(motionName))
                {
                    continue;
                }

                playerState.CurrentScores[motionName] = 0f;
                playerState.MotionScores.Add(new MotionScore
                {
                    motionName = motionName,
                    confidence = 0f
                });
            }
        }

        private void NotifyPlayerMotionChangedIfNeeded(PlayerMotionState playerState)
        {
            bool motionNameChanged = playerState.DetectedMotionName != playerState.LastNotifiedMotionName;
            bool confidenceChanged = Mathf.Abs(playerState.DetectedMotionConfidence - playerState.LastNotifiedMotionConfidence) >= MotionChangeEventConfidenceDelta;
            if (!motionNameChanged && !confidenceChanged)
            {
                return;
            }

            playerState.LastNotifiedMotionName = playerState.DetectedMotionName;
            playerState.LastNotifiedMotionConfidence = playerState.DetectedMotionConfidence;
            OnPlayerMotionChanged?.Invoke(playerState.PlayerSlot, playerState.DetectedMotionName, playerState.DetectedMotionConfidence);

            if (playerState.PlayerSlot == ResolveSelectedPlayerSlot())
            {
                OnMotionChanged?.Invoke(playerState.DetectedMotionName, playerState.DetectedMotionConfidence);
            }
        }

        private void NotifyPlayerMotionScoresUpdated(PlayerMotionState playerState)
        {
            OnPlayerMotionScoresUpdated?.Invoke(playerState.PlayerSlot, playerState.MotionScores);

            if (playerState.PlayerSlot == ResolveSelectedPlayerSlot())
            {
                OnMotionScoresUpdated?.Invoke(playerState.MotionScores);
            }
        }

