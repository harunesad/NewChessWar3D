        private static float EstimateTemplateLandmarkScale2D(List<MotionFrameTemplate> frames)
        {
            if (frames == null || frames.Count == 0)
            {
                return 0.5f;
            }

            float total = 0f;
            int count = 0;

            for (int frameIndex = 0; frameIndex < frames.Count; frameIndex++)
            {
                MotionFrameTemplate frame = frames[frameIndex];
                if (frame == null || frame.trackedLandmarks == null || frame.trackedLandmarks.Length < 2)
                {
                    continue;
                }

                Vector2 min = new Vector2(float.MaxValue, float.MaxValue);
                Vector2 max = new Vector2(float.MinValue, float.MinValue);
                for (int i = 0; i < frame.trackedLandmarks.Length; i++)
                {
                    Vector2 point = frame.trackedLandmarks[i].Position;
                    min = Vector2.Min(min, point);
                    max = Vector2.Max(max, point);
                }

                float diagonal = Vector2.Distance(min, max);
                if (diagonal <= MinVectorEpsilon)
                {
                    continue;
                }

                total += diagonal;
                count++;
            }

            if (count <= 0)
            {
                return 0.5f;
            }

            return total / count;
        }

        private static float EstimateTemplateLandmarkScale3D(List<MotionFrameTemplate> frames)
        {
            if (frames == null || frames.Count == 0)
            {
                return 1f;
            }

            float total = 0f;
            int count = 0;

            for (int frameIndex = 0; frameIndex < frames.Count; frameIndex++)
            {
                MotionFrameTemplate frame = frames[frameIndex];
                if (frame == null || frame.trackedWorldLandmarks == null || frame.trackedWorldLandmarks.Length < 3)
                {
                    continue;
                }

                Vector3 min = new Vector3(float.MaxValue, float.MaxValue, float.MaxValue);
                Vector3 max = new Vector3(float.MinValue, float.MinValue, float.MinValue);
                for (int i = 0; i < frame.trackedWorldLandmarks.Length; i++)
                {
                    Vector3 point = frame.trackedWorldLandmarks[i].Position;
                    min = Vector3.Min(min, point);
                    max = Vector3.Max(max, point);
                }

                float diagonal = Vector3.Distance(min, max);
                if (diagonal <= MinVectorEpsilon)
                {
                    continue;
                }

                total += diagonal;
                count++;
            }

            if (count <= 0)
            {
                return 1f;
            }

            return total / count;
        }

        private static void EnsureMinimumMovingEntries(bool[] movingMask, bool[] seenMask, float[] motionScore, int minimumRequired)
        {
            if (movingMask == null || seenMask == null || motionScore == null || minimumRequired <= 0)
            {
                return;
            }

            int movingCount = 0;
            int seenCount = 0;
            for (int i = 0; i < movingMask.Length && i < seenMask.Length; i++)
            {
                if (seenMask[i])
                {
                    seenCount++;
                }

                if (movingMask[i])
                {
                    movingCount++;
                }
            }

            int targetCount = Mathf.Min(minimumRequired, seenCount);
            while (movingCount < targetCount)
            {
                int bestIndex = -1;
                float bestScore = float.NegativeInfinity;
                for (int i = 0; i < movingMask.Length && i < seenMask.Length && i < motionScore.Length; i++)
                {
                    if (!seenMask[i] || movingMask[i])
                    {
                        continue;
                    }

                    if (motionScore[i] > bestScore)
                    {
                        bestScore = motionScore[i];
                        bestIndex = i;
                    }
                }

                if (bestIndex < 0)
                {
                    break;
                }

                movingMask[bestIndex] = true;
                movingCount++;
            }
        }

        private static void EnsureMinimumMovingAngles(HashSet<ulong> movingAngleKeys, Dictionary<ulong, float> angleScores, int minimumRequired)
        {
            if (movingAngleKeys == null || angleScores == null || minimumRequired <= 0 || angleScores.Count == 0)
            {
                return;
            }

            int targetCount = Mathf.Min(minimumRequired, angleScores.Count);
            while (movingAngleKeys.Count < targetCount)
            {
                bool found = false;
                ulong bestKey = 0UL;
                float bestScore = float.NegativeInfinity;

                foreach (KeyValuePair<ulong, float> pair in angleScores)
                {
                    if (movingAngleKeys.Contains(pair.Key))
                    {
                        continue;
                    }

                    if (!found || pair.Value > bestScore)
                    {
                        found = true;
                        bestKey = pair.Key;
                        bestScore = pair.Value;
                    }
                }

                if (!found)
                {
                    break;
                }

                movingAngleKeys.Add(bestKey);
            }
        }

        private static ulong CreateAngleKey(int a, int b, int c)
        {
            int left = Mathf.Min(a, c);
            int right = Mathf.Max(a, c);
            return ((ulong)(uint)left << 20) | ((ulong)(uint)b << 10) | (uint)right;
        }

        private static bool TryParseTrackedPosePointData(TrackedPosePoint[] trackedPointData, out PosePointSample[] trackedLandmarks)
        {
            trackedLandmarks = null;
            if (trackedPointData == null || trackedPointData.Length == 0)
            {
                return false;
            }

            List<PosePointSample> points = new List<PosePointSample>(trackedPointData.Length);
            for (int i = 0; i < trackedPointData.Length; i++)
            {
                TrackedPosePoint point = trackedPointData[i];
                if (!IsValidLandmarkIndex(point.index))
                {
                    continue;
                }

                points.Add(new PosePointSample(point.index, new Vector2(point.x, point.y)));
            }

            if (points.Count < 2)
            {
                return false;
            }

            trackedLandmarks = points.ToArray();
            return true;
        }

        private static bool TryParseTrackedPoseAngleData(TrackedPoseAngle[] trackedAngleData, out PoseAngleSample[] trackedAngles)
        {
            trackedAngles = null;
            if (trackedAngleData == null || trackedAngleData.Length == 0)
            {
                return false;
            }

            List<PoseAngleSample> angles = new List<PoseAngleSample>(trackedAngleData.Length);
            for (int i = 0; i < trackedAngleData.Length; i++)
            {
                TrackedPoseAngle angle = trackedAngleData[i];
                if (!IsValidLandmarkIndex(angle.a) ||
                    !IsValidLandmarkIndex(angle.b) ||
                    !IsValidLandmarkIndex(angle.c))
                {
                    continue;
                }

                angles.Add(new PoseAngleSample(angle.a, angle.b, angle.c, Mathf.Clamp(angle.angle, 0f, 180f)));
            }

            if (angles.Count == 0)
            {
                return false;
            }

            trackedAngles = angles.ToArray();
            return true;
        }

        private static bool TryParseTrackedPoseWorldPointData(TrackedPoseWorldPoint[] trackedWorldPointData, out PoseWorldPointSample[] trackedWorldLandmarks)
        {
            trackedWorldLandmarks = null;
            if (trackedWorldPointData == null || trackedWorldPointData.Length == 0)
            {
                return false;
            }

            List<PoseWorldPointSample> points = new List<PoseWorldPointSample>(trackedWorldPointData.Length);
            for (int i = 0; i < trackedWorldPointData.Length; i++)
            {
                TrackedPoseWorldPoint point = trackedWorldPointData[i];
                if (!IsValidLandmarkIndex(point.index))
                {
                    continue;
                }

                points.Add(new PoseWorldPointSample(point.index, new Vector3(point.x, point.y, point.z)));
            }

            if (points.Count < 3)
            {
                return false;
            }

            trackedWorldLandmarks = points.ToArray();
            return true;
        }

        private static bool IsValidLandmarkIndex(int index)
        {
            return index >= 0 && index < LandmarkCount;
        }
    }
