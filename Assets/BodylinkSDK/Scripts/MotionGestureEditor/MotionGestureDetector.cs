        private void RebuildMotionTemplates()
        {
            templates.Clear();
            maxTemplateDuration = 1f;

            if (motionFiles != null)
            {
                for (int i = 0; i < motionFiles.Count; i++)
                {
                    MotionFileReference motionEntry = motionFiles[i];
                    if (motionEntry == null || motionEntry.motionFile == null)
                    {
                        continue;
                    }

                    if (!TryParseMotionJson(motionEntry.motionFile.text, out MotionFrameTemplate[] frames, out float duration))
                    {
                        Debug.LogWarning("[MotionGestureDetector] Invalid motion JSON (frames with trackedLandmarks, trackedAngles, and/or trackedWorldLandmarks required): " + motionEntry.motionFile.name);
                        continue;
                    }

                    MotionTemplate template = new MotionTemplate
                    {
                        motionName = ResolveMotionName(motionEntry),
                        duration = duration,
                        frames = frames
                    };

                    templates.Add(template);
                    maxTemplateDuration = Mathf.Max(maxTemplateDuration, duration);
                }
            }

            for (int i = 0; i < playerStates.Length; i++)
            {
                PlayerMotionState playerState = playerStates[i];
                playerState.LiveSamples.Clear();
                playerState.NextSampleTime = 0f;
                PopulateZeroScoresForTemplates(playerState);
            }
        }

        private static string ResolveMotionName(MotionFileReference motionEntry)
        {
            if (!string.IsNullOrWhiteSpace(motionEntry.motionName))
            {
                return motionEntry.motionName.Trim();
            }

            if (motionEntry.motionFile != null)
            {
                return motionEntry.motionFile.name;
            }

            return "UnnamedMotion";
        }

        private static bool TryParseMotionJson(string json, out MotionFrameTemplate[] frames, out float duration)
        {
            frames = null;
            duration = 0f;
            if (string.IsNullOrWhiteSpace(json))
            {
                return false;
            }

            MotionJsonData data = JsonUtility.FromJson<MotionJsonData>(json);
            if (data == null || data.frames == null || data.frames.Length == 0)
            {
                return false;
            }

            List<MotionFrameTemplate> parsedFrames = new List<MotionFrameTemplate>(data.frames.Length);
            for (int i = 0; i < data.frames.Length; i++)
            {
                MotionFrameJsonData frameData = data.frames[i];
                if (frameData == null)
                {
                    continue;
                }

                bool hasTrackedLandmarks = TryParseTrackedPosePointData(frameData.trackedLandmarks, out PosePointSample[] trackedLandmarks);
                bool hasTrackedAngles = TryParseTrackedPoseAngleData(frameData.trackedAngles, out PoseAngleSample[] trackedAngles);
                bool hasTrackedWorldLandmarks = TryParseTrackedPoseWorldPointData(frameData.trackedWorldLandmarks, out PoseWorldPointSample[] trackedWorldLandmarks);
                if (!hasTrackedLandmarks && !hasTrackedAngles && !hasTrackedWorldLandmarks)
                {
                    continue;
                }

                parsedFrames.Add(new MotionFrameTemplate
                {
                    time = Mathf.Max(0f, frameData.time),
                    trackedLandmarks = trackedLandmarks,
                    trackedAngles = trackedAngles,
                    trackedWorldLandmarks = trackedWorldLandmarks
                });
            }

            if (parsedFrames.Count < 2)
            {
                return false;
            }

            parsedFrames.Sort((left, right) => left.time.CompareTo(right.time));

            float firstTime = parsedFrames[0].time;
            for (int i = 0; i < parsedFrames.Count; i++)
            {
                parsedFrames[i].time -= firstTime;
            }

            float inferredDuration = parsedFrames[parsedFrames.Count - 1].time;
            duration = data.duration > 0f ? data.duration - firstTime : inferredDuration;
            duration = Mathf.Max(duration, inferredDuration, 0.05f);

            for (int i = 0; i < parsedFrames.Count; i++)
            {
                parsedFrames[i].normalizedTime = duration > 0f ? Mathf.Clamp01(parsedFrames[i].time / duration) : 0f;
            }

            ApplyDeltaBasedMotionFiltering(parsedFrames);

            parsedFrames[0].normalizedTime = 0f;
            parsedFrames[parsedFrames.Count - 1].normalizedTime = 1f;

            frames = parsedFrames.ToArray();
            return true;
        }

        private static void ApplyDeltaBasedMotionFiltering(List<MotionFrameTemplate> frames)
        {
            if (frames == null || frames.Count == 0)
            {
                return;
            }

            float[] landmarkMaxDelta = new float[LandmarkCount];
            float[] landmarkTotalDelta = new float[LandmarkCount];
            bool[] landmarkSeen = new bool[LandmarkCount];
            Vector2[] previousLandmarks = new Vector2[LandmarkCount];
            bool[] hasPreviousLandmarks = new bool[LandmarkCount];

            float[] worldMaxDelta = new float[LandmarkCount];
            float[] worldTotalDelta = new float[LandmarkCount];
            bool[] worldSeen = new bool[LandmarkCount];
            Vector3[] previousWorldLandmarks = new Vector3[LandmarkCount];
            bool[] hasPreviousWorldLandmarks = new bool[LandmarkCount];

            for (int frameIndex = 0; frameIndex < frames.Count; frameIndex++)
            {
                MotionFrameTemplate frame = frames[frameIndex];
                if (frame == null)
                {
                    continue;
                }

                PosePointSample[] trackedLandmarks = frame.trackedLandmarks;
                if (trackedLandmarks != null)
                {
                    for (int i = 0; i < trackedLandmarks.Length; i++)
                    {
                        PosePointSample sample = trackedLandmarks[i];
                        if (!IsValidLandmarkIndex(sample.Index))
                        {
                            continue;
                        }

                        int index = sample.Index;
                        landmarkSeen[index] = true;
                        if (hasPreviousLandmarks[index])
                        {
                            float delta = Vector2.Distance(previousLandmarks[index], sample.Position);
                            landmarkMaxDelta[index] = Mathf.Max(landmarkMaxDelta[index], delta);
                            landmarkTotalDelta[index] += delta;
                        }

                        previousLandmarks[index] = sample.Position;
                        hasPreviousLandmarks[index] = true;
                    }
                }

                PoseWorldPointSample[] trackedWorldLandmarks = frame.trackedWorldLandmarks;
                if (trackedWorldLandmarks != null)
                {
                    for (int i = 0; i < trackedWorldLandmarks.Length; i++)
                    {
                        PoseWorldPointSample sample = trackedWorldLandmarks[i];
                        if (!IsValidLandmarkIndex(sample.Index))
                        {
                            continue;
                        }

                        int index = sample.Index;
                        worldSeen[index] = true;
                        if (hasPreviousWorldLandmarks[index])
                        {
                            float delta = Vector3.Distance(previousWorldLandmarks[index], sample.Position);
                            worldMaxDelta[index] = Mathf.Max(worldMaxDelta[index], delta);
                            worldTotalDelta[index] += delta;
                        }

                        previousWorldLandmarks[index] = sample.Position;
                        hasPreviousWorldLandmarks[index] = true;
                    }
                }
            }

            float[] landmarkMotionScore = new float[LandmarkCount];
            bool[] movingLandmarkMask = new bool[LandmarkCount];
            float landmarkScale = EstimateTemplateLandmarkScale2D(frames);
            float landmarkPeakThreshold = Mathf.Clamp(landmarkScale * MotionDeltaScaleFactor2D, MotionDeltaMin2D, MotionDeltaMax2D);
            float landmarkAccumThreshold = landmarkPeakThreshold * MotionDeltaAccumulationMultiplier;

            for (int index = 0; index < LandmarkCount; index++)
            {
                landmarkMotionScore[index] = landmarkMaxDelta[index] + (landmarkTotalDelta[index] * 0.25f);
                bool isMoving = landmarkSeen[index] &&
                    (landmarkMaxDelta[index] >= landmarkPeakThreshold ||
                     landmarkTotalDelta[index] >= landmarkAccumThreshold);

                if (!isMoving &&
                    landmarkSeen[index] &&
                    IsCoreLandmarkIndex(index) &&
                    landmarkMaxDelta[index] >= landmarkPeakThreshold * MotionDeltaAssistMultiplier)
                {
                    isMoving = true;
                }

                movingLandmarkMask[index] = isMoving;
            }

            EnsureMinimumMovingEntries(movingLandmarkMask, landmarkSeen, landmarkMotionScore, minimumRequired: 2);

            float[] worldMotionScore = new float[LandmarkCount];
            bool[] movingWorldMask = new bool[LandmarkCount];
            float worldScale = EstimateTemplateLandmarkScale3D(frames);
            float worldPeakThreshold = Mathf.Clamp(worldScale * MotionDeltaScaleFactor3D, MotionDeltaMin3D, MotionDeltaMax3D);
            float worldAccumThreshold = worldPeakThreshold * 1.6f;
            int worldSeenCount = 0;

            for (int index = 0; index < LandmarkCount; index++)
            {
                if (worldSeen[index])
                {
                    worldSeenCount++;
                }

                worldMotionScore[index] = worldMaxDelta[index] + (worldTotalDelta[index] * 0.25f);
                bool isMoving = worldSeen[index] &&
                    (worldMaxDelta[index] >= worldPeakThreshold ||
                     worldTotalDelta[index] >= worldAccumThreshold);

                if (!isMoving &&
                    worldSeen[index] &&
                    movingLandmarkMask[index] &&
                    worldMaxDelta[index] >= worldPeakThreshold * MotionDeltaAssistMultiplier)
                {
                    isMoving = true;
                }

                movingWorldMask[index] = isMoving;
            }

            if (worldSeenCount >= 3)
            {
                EnsureMinimumMovingEntries(movingWorldMask, worldSeen, worldMotionScore, minimumRequired: 3);
            }

            Dictionary<ulong, AngleMotionAccumulator> angleAccumulators = new Dictionary<ulong, AngleMotionAccumulator>();
            for (int frameIndex = 0; frameIndex < frames.Count; frameIndex++)
            {
                MotionFrameTemplate frame = frames[frameIndex];
                if (frame == null || frame.trackedAngles == null)
                {
                    continue;
                }

                for (int i = 0; i < frame.trackedAngles.Length; i++)
                {
                    PoseAngleSample sample = frame.trackedAngles[i];
                    ulong key = CreateAngleKey(sample.A, sample.B, sample.C);
                    if (!angleAccumulators.TryGetValue(key, out AngleMotionAccumulator accumulator))
                    {
                        accumulator = new AngleMotionAccumulator(sample.A, sample.B, sample.C);
                        angleAccumulators[key] = accumulator;
                    }

                    if (accumulator.HasLastAngle)
                    {
                        float delta = Mathf.Abs(Mathf.DeltaAngle(accumulator.LastAngle, sample.Angle));
                        accumulator.MaxDelta = Mathf.Max(accumulator.MaxDelta, delta);
                        accumulator.TotalDelta += delta;
                    }

                    accumulator.LastAngle = sample.Angle;
                    accumulator.HasLastAngle = true;
                }
            }

            Dictionary<ulong, float> angleMotionScoreByKey = new Dictionary<ulong, float>(angleAccumulators.Count);
            HashSet<ulong> movingAngleKeys = new HashSet<ulong>();
            foreach (KeyValuePair<ulong, AngleMotionAccumulator> pair in angleAccumulators)
            {
                AngleMotionAccumulator accumulator = pair.Value;
                float score = accumulator.MaxDelta + (accumulator.TotalDelta * 0.2f);
                angleMotionScoreByKey[pair.Key] = score;

                bool isMoving = accumulator.MaxDelta >= AngleMotionDeltaThreshold ||
                    accumulator.TotalDelta >= AngleMotionAccumulationThreshold;

                if (!isMoving &&
                    (movingLandmarkMask[accumulator.A] || movingLandmarkMask[accumulator.B] || movingLandmarkMask[accumulator.C]) &&
                    accumulator.MaxDelta >= AngleMotionDeltaThreshold * MotionDeltaAssistMultiplier)
                {
                    isMoving = true;
                }

                if (isMoving)
                {
                    movingAngleKeys.Add(pair.Key);
                }
            }

            EnsureMinimumMovingAngles(movingAngleKeys, angleMotionScoreByKey, minimumRequired: 1);

            for (int frameIndex = 0; frameIndex < frames.Count; frameIndex++)
            {
                MotionFrameTemplate frame = frames[frameIndex];
                if (frame == null)
                {
                    continue;
                }

                PosePointSample[] filteredLandmarks = FilterLandmarkSamplesByMotion(frame.trackedLandmarks, movingLandmarkMask, landmarkMotionScore, minimumRequired: 2);
                PoseWorldPointSample[] filteredWorldLandmarks = FilterWorldLandmarkSamplesByMotion(frame.trackedWorldLandmarks, movingWorldMask, worldMotionScore, minimumRequired: 3);
                PoseAngleSample[] filteredAngles = FilterAngleSamplesByMotion(frame.trackedAngles, movingAngleKeys, angleMotionScoreByKey, minimumRequired: 1);

                bool hasLandmarkData = filteredLandmarks != null && filteredLandmarks.Length >= 2;
                bool hasAngleData = filteredAngles != null && filteredAngles.Length > 0;
                bool hasWorldData = filteredWorldLandmarks != null && filteredWorldLandmarks.Length >= 3;

                if (!hasLandmarkData && !hasAngleData && !hasWorldData)
                {
                    continue;
                }

                frame.trackedLandmarks = hasLandmarkData ? filteredLandmarks : null;
                frame.trackedAngles = hasAngleData ? filteredAngles : null;
                frame.trackedWorldLandmarks = hasWorldData ? filteredWorldLandmarks : null;
            }
        }

        private static PosePointSample[] FilterLandmarkSamplesByMotion(
            PosePointSample[] samples,
            bool[] movingMask,
            float[] motionScores,
            int minimumRequired)
        {
            if (samples == null || samples.Length == 0)
            {
                return null;
            }

            bool[] include = new bool[samples.Length];
            int includeCount = 0;

            for (int i = 0; i < samples.Length; i++)
            {
                int index = samples[i].Index;
                if (IsValidLandmarkIndex(index) && movingMask != null && index < movingMask.Length && movingMask[index])
                {
                    include[i] = true;
                    includeCount++;
                }
            }

            int targetCount = Mathf.Min(Mathf.Max(minimumRequired, 1), samples.Length);
            while (includeCount < targetCount)
            {
                int bestIndex = -1;
                float bestScore = float.NegativeInfinity;
                for (int i = 0; i < samples.Length; i++)
                {
                    if (include[i])
                    {
                        continue;
                    }

                    int index = samples[i].Index;
                    float score = IsValidLandmarkIndex(index) && motionScores != null && index < motionScores.Length
                        ? motionScores[index]
                        : 0f;

                    if (score > bestScore)
                    {
                        bestScore = score;
                        bestIndex = i;
                    }
                }

                if (bestIndex < 0)
                {
                    break;
                }

                include[bestIndex] = true;
                includeCount++;
            }

            if (includeCount <= 0)
            {
                return null;
            }

            PosePointSample[] filtered = new PosePointSample[includeCount];
            int writeIndex = 0;
            for (int i = 0; i < samples.Length; i++)
            {
                if (!include[i])
                {
                    continue;
                }

                filtered[writeIndex++] = samples[i];
            }

            return filtered;
        }

