            int targetCount = Mathf.Min(Mathf.Max(minimumRequired, 1), samples.Length);
            while (includeCount < targetCount)
            {
                int bestIndex = -1;
                float bestScore = float.NegativeInfinity;
                for (int i = 0; i < samples.Length; i++)
                {
                    if (include[i])
                    {
                        continue;
                    }

                    ulong key = CreateAngleKey(samples[i].A, samples[i].B, samples[i].C);
                    float score = 0f;
                    if (angleMotionScores != null && angleMotionScores.TryGetValue(key, out float motionScore))
                    {
                        score = motionScore;
                    }

                    if (score > bestScore)
                    {
                        bestScore = score;
                        bestIndex = i;
                    }
