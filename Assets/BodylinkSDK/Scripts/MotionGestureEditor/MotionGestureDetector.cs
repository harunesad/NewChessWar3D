        private int ResolveSelectedPlayerSlot()
        {
            if (Bodylink.Instance == null || !Bodylink.Instance.isMultiplayerEnabled)
            {
                return 0;
            }

            if (Bodylink.Instance.bodylinkAvatar == null ||
                Bodylink.Instance.bodylinkAvatar.players == null ||
                Bodylink.Instance.bodylinkAvatar.players.Length == 0)
            {
                return 0;
            }

            return Mathf.Clamp(playerSlot, 0, Mathf.Min(Bodylink.Instance.bodylinkAvatar.players.Length - 1, MaxSupportedPlayers - 1));
        }

        private PlayerMotionState GetPlayerState(int targetPlayerSlot)
        {
            int slot = Mathf.Clamp(targetPlayerSlot, 0, MaxSupportedPlayers - 1);
            return playerStates[slot];
        }

        private bool TryReadPlayerLandmarks(int slot, Vector2[] landmarksOut, Vector3[] worldLandmarksOut, float[] visibilityOut, out bool hasWorldLandmarks)
        {
            hasWorldLandmarks = false;
            if (players == null || landmarksOut == null || visibilityOut == null || worldLandmarksOut == null)
            {
                return false;
            }

            if (slot < 0 || slot >= players.Length || players[slot] == null)
            {
                return false;
            }

            List<NormalizedLandmark> landmarks = players[slot].bodyRawPoints2D;
            if (landmarks == null || landmarks.Count < LandmarkCount)
            {
                return false;
            }

            List<Landmark> worldLandmarks = players[slot].bodyRawPoints3D;
            hasWorldLandmarks = worldLandmarks != null && worldLandmarks.Count >= LandmarkCount;

            for (int i = 0; i < LandmarkCount; i++)
            {
                landmarksOut[i] = new Vector2(landmarks[i].x, landmarks[i].y);

                if (hasWorldLandmarks)
                {
                    worldLandmarksOut[i] = new Vector3(worldLandmarks[i].x, worldLandmarks[i].y, worldLandmarks[i].z);
                }
                else
                {
                    worldLandmarksOut[i] = Vector3.zero;
                }

                float visibility = landmarks[i].visibility.GetValueOrDefault(1f);
                float presence = landmarks[i].presence.GetValueOrDefault(1f);
                visibilityOut[i] = Mathf.Max(visibility, presence);
            }

            return true;
        }

        private void PushLiveSample(PlayerMotionState playerState, float sampleTime, Vector2[] landmarks, Vector3[] worldLandmarks, float[] visibility, bool hasWorldLandmarks)
        {
            if (playerState == null)
            {
                return;
            }

            Vector2[] landmarksCopy = new Vector2[LandmarkCount];
            Vector3[] worldLandmarksCopy = new Vector3[LandmarkCount];
            float[] visibilityCopy = new float[LandmarkCount];
            Array.Copy(landmarks, landmarksCopy, LandmarkCount);
            Array.Copy(worldLandmarks, worldLandmarksCopy, LandmarkCount);
            Array.Copy(visibility, visibilityCopy, LandmarkCount);

            playerState.LiveSamples.Add(new LivePoseSample(sampleTime, landmarksCopy, worldLandmarksCopy, visibilityCopy, hasWorldLandmarks));
            PruneLiveSamples(playerState.LiveSamples, sampleTime);
        }

        private void PruneLiveSamples(List<LivePoseSample> samples, float now)
        {
            if (samples == null)
            {
                return;
            }

            float keepDuration = Mathf.Max((maxTemplateDuration * Mathf.Max(maxTimeScale, 1f)) + 0.8f, 1.5f);
            float minTime = now - keepDuration;

            int removeCount = 0;
            while (removeCount < samples.Count && samples[removeCount].Time < minTime)
            {
                removeCount++;
            }

            if (removeCount > 0)
            {
                samples.RemoveRange(0, removeCount);
            }
        }

        private void EvaluateMotionTemplates(PlayerMotionState playerState, float now)
        {
            if (playerState == null)
            {
                return;
            }

            playerState.CurrentScores.Clear();
            playerState.MotionScores.Clear();

            Dictionary<string, float> bestScoresByMotionName = new Dictionary<string, float>(StringComparer.Ordinal);
            List<string> motionNamesInDisplayOrder = new List<string>(templates.Count);

            string bestMotion = "Analyzing";
            float bestConfidence = 0f;

            for (int i = 0; i < templates.Count; i++)
            {
                MotionTemplate template = templates[i];
                float confidence = CalculateMotionConfidence(template, playerState.LiveSamples);

                string motionName = ResolveTemplateDisplayName(template.motionName);

                if (bestScoresByMotionName.TryGetValue(motionName, out float existing))
                {
                    if (confidence > existing)
                    {
                        bestScoresByMotionName[motionName] = confidence;
                    }
                }
                else
                {
                    bestScoresByMotionName[motionName] = confidence;
                    motionNamesInDisplayOrder.Add(motionName);
                }
            }

            for (int i = 0; i < motionNamesInDisplayOrder.Count; i++)
            {
                string motionName = motionNamesInDisplayOrder[i];
                float confidence = bestScoresByMotionName[motionName];
                playerState.CurrentScores[motionName] = confidence;
                playerState.MotionScores.Add(new MotionScore
                {
                    motionName = motionName,
                    confidence = confidence
                });

                if (confidence > bestConfidence)
                {
                    bestConfidence = confidence;
                    bestMotion = motionName;
                }
            }

            playerState.DetectedMotionConfidence = Mathf.Clamp01(bestConfidence);
            playerState.DetectedMotionName = playerState.DetectedMotionConfidence >= detectionThreshold ? bestMotion : "Analyzing";
            NotifyPlayerMotionScoresUpdated(playerState);
            NotifyPlayerMotionChangedIfNeeded(playerState);

            TryTriggerDetectedMotion(playerState, now);

            if (debugEnabled &&
                (playerState.DetectedMotionName != playerState.LastLoggedMotionName ||
                 Mathf.Abs(playerState.DetectedMotionConfidence - playerState.LastLoggedMotionConfidence) > 0.01f))
            {
                Debug.Log("[MotionGestureDetector] Player " + (playerState.PlayerSlot + 1) + " Motion: " +
                          playerState.DetectedMotionName + " (" + playerState.DetectedMotionConfidence.ToString("0.000") + ")");
                playerState.LastLoggedMotionName = playerState.DetectedMotionName;
                playerState.LastLoggedMotionConfidence = playerState.DetectedMotionConfidence;
            }
        }

        private void TryTriggerDetectedMotion(PlayerMotionState playerState, float now)
        {
            if (playerState == null ||
                playerState.DetectedMotionName == "Analyzing" ||
                playerState.DetectedMotionConfidence < detectionThreshold)
            {
                return;
            }

            bool isDifferentMotion = !string.Equals(playerState.LastTriggeredMotionName, playerState.DetectedMotionName, StringComparison.Ordinal);
            bool cooldownElapsed = (now - playerState.LastTriggerTime) >= triggerCooldown;
            if (!isDifferentMotion && !cooldownElapsed)
            {
                return;
            }

            OnGestureDetect(playerState.PlayerSlot, playerState.DetectedMotionName, playerState.DetectedMotionConfidence);
            playerState.LastTriggeredMotionName = playerState.DetectedMotionName;
            playerState.LastTriggerTime = now;
        }

        private float CalculateMotionConfidence(MotionTemplate template, List<LivePoseSample> samples)
        {
            if (template == null || template.frames == null || template.frames.Length < 2 || samples == null || samples.Count < 2)
            {
                return 0f;
            }

            float bestConfidence = 0f;
            float latestTime = samples[samples.Count - 1].Time;

            for (float scale = minTimeScale; scale <= maxTimeScale + 0.0001f; scale += timeScaleStep)
            {
                float windowDuration = Mathf.Max(template.duration * scale, 0.15f);
                float startTime = latestTime - windowDuration;
                if (samples[0].Time > startTime)
                {
                    continue;
                }

                if (!TryCalculateSequenceConfidence(template, samples, startTime, windowDuration, mirror: false, out float sequenceConfidence))
                {
                    continue;
                }

                if (includeMirroredComparison && TryCalculateSequenceConfidence(template, samples, startTime, windowDuration, mirror: true, out float mirroredConfidence))
                {
                    sequenceConfidence = Mathf.Max(sequenceConfidence, mirroredConfidence);
                }

                if (sequenceConfidence > bestConfidence)
                {
                    bestConfidence = sequenceConfidence;
                }
            }

            return bestConfidence;
        }

        private bool TryCalculateSequenceConfidence(MotionTemplate template, List<LivePoseSample> samples, float startTime, float windowDuration, bool mirror, out float confidence)
        {
            confidence = 0f;
            if (template == null || template.frames == null || template.frames.Length == 0 || samples == null || samples.Count == 0)
            {
                return false;
            }

            scoreBuffer.Clear();
            int validFrameCount = 0;
            int lowScoreCount = 0;

            for (int i = 0; i < template.frames.Length; i++)
            {
                MotionFrameTemplate frame = template.frames[i];
                float targetTime = startTime + (frame.normalizedTime * windowDuration);
                if (!TryInterpolateLivePose(samples, targetTime, interpolatedLandmarks, interpolatedWorldLandmarks, interpolatedVisibility, out bool hasLiveWorldLandmarks))
                {
                    continue;
                }

                if (!TryCalculateFrameConfidence(frame, interpolatedLandmarks, interpolatedWorldLandmarks, interpolatedVisibility, mirror, hasLiveWorldLandmarks, out float frameConfidence))
                {
                    continue;
                }

                scoreBuffer.Add(frameConfidence);
                validFrameCount++;
                if (frameConfidence < 0.35f)
                {
                    lowScoreCount++;
                }
            }

            int minimumRequiredFrames = Mathf.Max(2, Mathf.CeilToInt(template.frames.Length * 0.5f));
            if (validFrameCount < minimumRequiredFrames)
            {
                return false;
            }

            scoreBuffer.Sort();
            int dropCount = 0;
            if (scoreBuffer.Count >= 8)
            {
                dropCount = 2;
            }
            else if (scoreBuffer.Count >= 5)
            {
                dropCount = 1;
            }

            float baseConfidence = ComputeWeightedBaseScore(scoreBuffer, dropCount);
            float lowScoreRatio = lowScoreCount / (float)Mathf.Max(validFrameCount, 1);
            float mismatchPenalty = ComputeMismatchPenalty(lowScoreRatio, validFrameCount);
            float coverage = validFrameCount / (float)template.frames.Length;
            confidence = Mathf.Clamp01(baseConfidence * mismatchPenalty * coverage);
            return true;
        }

        private bool TryCalculateFrameConfidence(
            MotionFrameTemplate frame,
            Vector2[] liveLandmarks,
            Vector3[] liveWorldLandmarks,
            float[] liveVisibility,
            bool mirror,
            bool hasLiveWorldLandmarks,
            out float confidence)
        {
            confidence = 0f;
            bool hasAngleConfidence = TryCalculateAngleFrameConfidence(frame, liveLandmarks, liveVisibility, mirror, out float angleConfidence);
            bool hasLandmarkConfidence = TryCalculateLandmarkFrameConfidence(frame, liveLandmarks, liveVisibility, mirror, out float landmarkConfidence);
            bool hasWorldConfidence = TryCalculateWorldLandmarkFrameConfidence(frame, liveWorldLandmarks, liveVisibility, mirror, hasLiveWorldLandmarks, out float worldConfidence);

            if (!hasAngleConfidence && !hasLandmarkConfidence && !hasWorldConfidence)
            {
                return false;
            }

            if (hasWorldConfidence)
            {
                float angleWeight = hasAngleConfidence ? (frame.trackedAngles != null && frame.trackedAngles.Length >= 4 ? 0.25f : 0.15f) : 0f;
                float landmarkWeight = hasLandmarkConfidence ? 0.20f : 0f;
                float worldWeight = 1f - angleWeight - landmarkWeight;
                float blendedConfidence = (worldConfidence * worldWeight) +
                    (hasAngleConfidence ? angleConfidence * angleWeight : 0f) +
                    (hasLandmarkConfidence ? landmarkConfidence * landmarkWeight : 0f);
                confidence = Mathf.Max(worldConfidence, blendedConfidence);
                return true;
            }

            if (hasAngleConfidence && hasLandmarkConfidence)
            {
                float angleWeight = frame.trackedAngles != null && frame.trackedAngles.Length >= 4 ? 0.60f : 0.45f;
                float blendedConfidence = (angleConfidence * angleWeight) + (landmarkConfidence * (1f - angleWeight));
                confidence = Mathf.Max(angleConfidence, blendedConfidence);
                return true;
            }

            confidence = hasLandmarkConfidence ? landmarkConfidence : angleConfidence;
            return true;
        }

        private bool TryCalculateAngleFrameConfidence(MotionFrameTemplate frame, Vector2[] liveLandmarks, float[] liveVisibility, bool mirror, out float confidence)
        {
            if (prioritizeCorePoints &&
                TryCalculateAngleFrameConfidenceInternal(frame, liveLandmarks, liveVisibility, mirror, coreOnly: true, MinimumCoreAngleSamples, out confidence))
            {
                return true;
            }

            return TryCalculateAngleFrameConfidenceInternal(frame, liveLandmarks, liveVisibility, mirror, coreOnly: false, 1, out confidence);
        }

        private bool TryCalculateLandmarkFrameConfidence(MotionFrameTemplate frame, Vector2[] liveLandmarks, float[] liveVisibility, bool mirror, out float confidence)
        {
            confidence = 0f;

            if (frame == null ||
                frame.trackedLandmarks == null ||
                frame.trackedLandmarks.Length < 2 ||
                liveLandmarks == null ||
                liveLandmarks.Length < LandmarkCount)
            {
                return false;
            }

            bool collectedCorePoints = prioritizeCorePoints &&
                TryCollectLandmarkSources(frame, liveLandmarks, liveVisibility, mirror, coreOnly: true, MinimumCoreLandmarkSamples);
            if (!collectedCorePoints &&
                !TryCollectLandmarkSources(frame, liveLandmarks, liveVisibility, mirror, coreOnly: false, 2))
            {
                return false;
            }

            bool hasValidTransform = false;
            float bestConfidence = 0f;

            for (int transform = 0; transform < 4; transform++)
            {
                bool flipX = (transform & 1) != 0;
                bool flipY = (transform & 2) != 0;

                if (!TryCalculateLandmarkFrameConfidenceForTransform(flipX, flipY, out float candidateConfidence))
                {
                    continue;
                }

                hasValidTransform = true;
                if (candidateConfidence > bestConfidence)
                {
                    bestConfidence = candidateConfidence;
                }
            }

            if (!hasValidTransform)
            {
                return false;
            }

            confidence = bestConfidence;
            return true;
        }

        private bool TryCalculateLandmarkFrameConfidenceForTransform(bool flipX, bool flipY, out float confidence)
        {
            confidence = 0f;
            templatePointBuffer.Clear();
            livePointBuffer.Clear();

            for (int i = 0; i < templateSourcePointBuffer.Count; i++)
            {
                Vector2 templatePoint = templateSourcePointBuffer[i];
                Vector2 livePoint = liveSourcePointBuffer[i];

                if (flipX)
                {
                    livePoint.x = 1f - livePoint.x;
                }

                if (flipY)
                {
                    livePoint.y = 1f - livePoint.y;
                }

                templatePointBuffer.Add(templatePoint);
                livePointBuffer.Add(livePoint);
            }

            if (!TryNormalizePointSet(templatePointBuffer) || !TryNormalizePointSet(livePointBuffer))
            {
                return false;
            }

            float dot = 0f;
            float cross = 0f;
            for (int i = 0; i < templatePointBuffer.Count; i++)
            {
                Vector2 templatePoint = templatePointBuffer[i];
                Vector2 livePoint = livePointBuffer[i];
                dot += (livePoint.x * templatePoint.x) + (livePoint.y * templatePoint.y);
                cross += (livePoint.x * templatePoint.y) - (livePoint.y * templatePoint.x);
            }

            float rotation = Mathf.Atan2(cross, dot);
            float cos = Mathf.Cos(rotation);
            float sin = Mathf.Sin(rotation);

            float totalScore = 0f;
            int lowScoreCount = 0;

            for (int i = 0; i < templatePointBuffer.Count; i++)
            {
                Vector2 templatePoint = templatePointBuffer[i];
                Vector2 livePoint = livePointBuffer[i];
                Vector2 rotatedLivePoint = new Vector2(
                    (livePoint.x * cos) - (livePoint.y * sin),
                    (livePoint.x * sin) + (livePoint.y * cos));

                float distance = Vector2.Distance(rotatedLivePoint, templatePoint);
                float score = ScoreDistanceDelta(distance, LandmarkPerfectDistance, LandmarkToleranceDistance);
                totalScore += score;
                if (score < 0.35f)
                {
                    lowScoreCount++;
                }
            }

            float baseConfidence = totalScore / templatePointBuffer.Count;
            float lowScoreRatio = lowScoreCount / (float)templatePointBuffer.Count;
            float mismatchPenalty = ComputeMismatchPenalty(lowScoreRatio, templatePointBuffer.Count);
            confidence = Mathf.Clamp01(baseConfidence * mismatchPenalty);
            return true;
        }

        private bool TryCalculateWorldLandmarkFrameConfidence(
            MotionFrameTemplate frame,
            Vector3[] liveWorldLandmarks,
            float[] liveVisibility,
            bool mirror,
            bool hasLiveWorldLandmarks,
            out float confidence)
        {
            confidence = 0f;

            if (!hasLiveWorldLandmarks ||
                frame == null ||
                frame.trackedWorldLandmarks == null ||
                frame.trackedWorldLandmarks.Length < 3 ||
                liveWorldLandmarks == null ||
                liveWorldLandmarks.Length < LandmarkCount ||
                liveVisibility == null ||
                liveVisibility.Length < LandmarkCount)
            {
                return false;
            }

            bool collectedCorePoints = prioritizeCorePoints &&
                TryCollectWorldLandmarkSources(frame, liveWorldLandmarks, liveVisibility, mirror, coreOnly: true, MinimumCoreWorldSamples);
            if (!collectedCorePoints &&
                !TryCollectWorldLandmarkSources(frame, liveWorldLandmarks, liveVisibility, mirror, coreOnly: false, 3))
            {
                return false;
            }

            templateWorldPointBuffer.Clear();
            liveWorldPointBuffer.Clear();
            templateWorldPointBuffer.AddRange(templateWorldSourcePointBuffer);
            liveWorldPointBuffer.AddRange(liveWorldSourcePointBuffer);

            if (!TryNormalizePointSet3D(templateWorldPointBuffer) || !TryNormalizePointSet3D(liveWorldPointBuffer))
            {
                return false;
            }

            float totalScore = 0f;
            int pairCount = 0;
            int lowScoreCount = 0;

            for (int i = 0; i < templateWorldPointBuffer.Count - 1; i++)
            {
                for (int j = i + 1; j < templateWorldPointBuffer.Count; j++)
                {
                    float templateDistance = Vector3.Distance(templateWorldPointBuffer[i], templateWorldPointBuffer[j]);
                    float liveDistance = Vector3.Distance(liveWorldPointBuffer[i], liveWorldPointBuffer[j]);
                    float delta = Mathf.Abs(templateDistance - liveDistance);
                    float score = ScoreDistanceDelta(delta, WorldPairPerfectDistance, WorldPairToleranceDistance);
                    totalScore += score;
                    pairCount++;
                    if (score < 0.35f)
                    {
                        lowScoreCount++;
                    }
                }
            }

            if (pairCount <= 0)
            {
                return false;
            }

            float baseConfidence = totalScore / pairCount;
            float lowScoreRatio = lowScoreCount / (float)pairCount;
            float mismatchPenalty = ComputeMismatchPenalty(lowScoreRatio, pairCount);
            confidence = Mathf.Clamp01(baseConfidence * mismatchPenalty);
            return true;
        }

        private bool TryInterpolateLivePose(List<LivePoseSample> samples, float targetTime, Vector2[] landmarksOut, Vector3[] worldLandmarksOut, float[] visibilityOut, out bool hasWorldLandmarks)
        {
            hasWorldLandmarks = false;
            if (samples == null || samples.Count == 0 || landmarksOut == null || worldLandmarksOut == null || visibilityOut == null)
            {
                return false;
            }

            if (targetTime <= samples[0].Time)
            {
                Array.Copy(samples[0].Landmarks, landmarksOut, LandmarkCount);
                Array.Copy(samples[0].WorldLandmarks, worldLandmarksOut, LandmarkCount);
                Array.Copy(samples[0].Visibility, visibilityOut, LandmarkCount);
                hasWorldLandmarks = samples[0].HasWorldLandmarks;
                return true;
            }

            for (int i = 1; i < samples.Count; i++)
            {
                LivePoseSample right = samples[i];
                if (targetTime > right.Time)
                {
                    continue;
                }

                LivePoseSample left = samples[i - 1];
                float span = Mathf.Max(right.Time - left.Time, 0.0001f);
                float t = Mathf.Clamp01((targetTime - left.Time) / span);

                for (int j = 0; j < LandmarkCount; j++)
                {
                    landmarksOut[j] = Vector2.Lerp(left.Landmarks[j], right.Landmarks[j], t);
                    worldLandmarksOut[j] = Vector3.Lerp(left.WorldLandmarks[j], right.WorldLandmarks[j], t);
                    visibilityOut[j] = Mathf.Lerp(left.Visibility[j], right.Visibility[j], t);
                }

                hasWorldLandmarks = left.HasWorldLandmarks && right.HasWorldLandmarks;
                return true;
            }

            LivePoseSample last = samples[samples.Count - 1];
            if (targetTime > last.Time + 0.02f)
            {
                return false;
            }

            Array.Copy(last.Landmarks, landmarksOut, LandmarkCount);
            Array.Copy(last.WorldLandmarks, worldLandmarksOut, LandmarkCount);
            Array.Copy(last.Visibility, visibilityOut, LandmarkCount);
            hasWorldLandmarks = last.HasWorldLandmarks;
            return true;
        }

        private static bool TryNormalizePointSet(List<Vector2> points)
        {
            if (points == null || points.Count < 2)
            {
                return false;
            }

            Vector2 centroid = Vector2.zero;
            for (int i = 0; i < points.Count; i++)
            {
                centroid += points[i];
            }
            centroid /= points.Count;

            float sqrMagnitudeSum = 0f;
            for (int i = 0; i < points.Count; i++)
            {
                Vector2 centered = points[i] - centroid;
                points[i] = centered;
                sqrMagnitudeSum += centered.sqrMagnitude;
            }

            float scale = Mathf.Sqrt(sqrMagnitudeSum / points.Count);
            if (scale < MinTemplateSpread)
            {
                return false;
            }

            for (int i = 0; i < points.Count; i++)
            {
                points[i] /= scale;
            }

            return true;
        }

        private static bool TryNormalizePointSet3D(List<Vector3> points)
        {
            if (points == null || points.Count < 2)
            {
                return false;
            }

            Vector3 centroid = Vector3.zero;
            for (int i = 0; i < points.Count; i++)
            {
                centroid += points[i];
            }
            centroid /= points.Count;

            float sqrMagnitudeSum = 0f;
            for (int i = 0; i < points.Count; i++)
            {
                Vector3 centered = points[i] - centroid;
                points[i] = centered;
                sqrMagnitudeSum += centered.sqrMagnitude;
            }

            float scale = Mathf.Sqrt(sqrMagnitudeSum / points.Count);
            if (scale < MinTemplateSpread)
            {
                return false;
            }

            for (int i = 0; i < points.Count; i++)
            {
                points[i] /= scale;
            }

            return true;
        }

        private static float ComputeWeightedBaseScore(List<float> sortedScores, int startIndex)
        {
            if (sortedScores == null)
            {
                return 0f;
            }

            int count = sortedScores.Count - startIndex;
            if (count <= 0)
            {
                return 0f;
            }

            if (count == 1)
            {
                return sortedScores[sortedScores.Count - 1];
            }

            if (count == 2)
            {
                float low = sortedScores[startIndex];
                float high = sortedScores[startIndex + 1];
                return (high * 0.75f) + (low * 0.25f);
            }

            if (count == 3)
            {
                float low = sortedScores[startIndex];
                float mid = sortedScores[startIndex + 1];
                float high = sortedScores[startIndex + 2];
                return (high * 0.50f) + (mid * 0.30f) + (low * 0.20f);
            }

            float total = 0f;
            for (int i = startIndex; i < sortedScores.Count; i++)
            {
                total += sortedScores[i];
            }

            return total / count;
        }

        private static float ComputeMismatchPenalty(float lowScoreRatio, int sampleCount)
        {
            lowScoreRatio = Mathf.Clamp01(lowScoreRatio);
            int clampedSampleCount = Mathf.Max(sampleCount, 1);
            float validRatio = 1f - lowScoreRatio;

            if (clampedSampleCount <= 2)
            {
                return Mathf.Lerp(1f, validRatio, 0.25f);
            }

            if (clampedSampleCount <= 4)
            {
                return Mathf.Pow(validRatio, 0.65f);
            }

            if (clampedSampleCount <= 7)
            {
                return Mathf.Pow(validRatio, 1.00f);
            }

            return Mathf.Pow(validRatio, 1.6f);
        }

        private static float ScoreAngleDelta(float delta, float perfectWindow, float tolerance)
        {
            if (delta <= perfectWindow)
            {
                return 1f;
            }

            if (delta >= tolerance)
            {
                return 0f;
            }

            float normalized = Mathf.InverseLerp(perfectWindow, tolerance, delta);
            return 1f - (normalized * normalized);
        }

        private static float ScoreDistanceDelta(float distance, float perfectDistance, float tolerance)
        {
            if (distance <= perfectDistance)
            {
                return 1f;
            }

            if (distance >= tolerance)
            {
                return 0f;
            }

            float normalized = Mathf.InverseLerp(perfectDistance, tolerance, distance);
            return 1f - (normalized * normalized);
        }

        private static bool TryCalculateJointAngle(Vector2[] landmarks, int a, int b, int c, out float angle)
        {
            angle = 0f;
            if (landmarks == null ||
                a < 0 || a >= landmarks.Length ||
                b < 0 || b >= landmarks.Length ||
                c < 0 || c >= landmarks.Length)
            {
                return false;
            }

            Vector2 fromPivotToA = landmarks[a] - landmarks[b];
            Vector2 fromPivotToC = landmarks[c] - landmarks[b];

            float magnitudeA = fromPivotToA.magnitude;
            float magnitudeC = fromPivotToC.magnitude;
            if (magnitudeA < MinVectorEpsilon || magnitudeC < MinVectorEpsilon)
            {
                return false;
            }

            float dot = Vector2.Dot(fromPivotToA / magnitudeA, fromPivotToC / magnitudeC);
            dot = Mathf.Clamp(dot, -1f, 1f);
            angle = Mathf.Acos(dot) * Mathf.Rad2Deg;
            return true;
        }

