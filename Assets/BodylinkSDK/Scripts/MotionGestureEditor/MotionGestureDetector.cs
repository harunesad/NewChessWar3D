        public override void ProcessGesture()
        {
            if (Bodylink.Instance == null || !Bodylink.Instance.IsInitialized)
            {
                SetNoMatchStateForAllPlayers("Analyzing");
                SyncSelectedPlayerRealtimeOutput();
                return;
            }

            if (templates.Count == 0)
            {
                SetNoMatchStateForAllPlayers("No Motion Files");
                SyncSelectedPlayerRealtimeOutput();
                return;
            }

            float now = Time.time;
            int trackedPlayerCount = Bodylink.Instance.isMultiplayerEnabled ? MaxSupportedPlayers : 1;
            for (int slot = 0; slot < MaxSupportedPlayers; slot++)
            {
                PlayerMotionState playerState = GetPlayerState(slot);
                if (slot >= trackedPlayerCount)
                {
                    SetNoMatchState(playerState, "Analyzing");
                    continue;
                }

                if (!TryReadPlayerLandmarks(slot, currentLandmarks, currentWorldLandmarks, currentVisibility, out bool hasWorldLandmarks))
                {
                    SetNoMatchState(playerState, "Analyzing");
                    continue;
                }

                if (now >= playerState.NextSampleTime)
                {
                    PushLiveSample(playerState, now, currentLandmarks, currentWorldLandmarks, currentVisibility, hasWorldLandmarks);
                    playerState.NextSampleTime = now + (1f / Mathf.Max(1f, samplingRate));
                }

                if (playerState.LiveSamples.Count < 3)
                {
                    SetNoMatchState(playerState, "Analyzing");
                    continue;
                }

                EvaluateMotionTemplates(playerState, now);
            }

            SyncSelectedPlayerRealtimeOutput();
        }

