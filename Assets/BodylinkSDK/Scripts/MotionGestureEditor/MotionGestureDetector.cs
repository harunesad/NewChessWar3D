        private bool TryCalculateAngleFrameConfidenceInternal(
            MotionFrameTemplate frame,
            Vector2[] liveLandmarks,
            float[] liveVisibility,
            bool mirror,
            bool coreOnly,
            int minimumRequiredSamples,
            out float confidence)
        {
            confidence = 0f;
            if (frame == null || frame.trackedAngles == null || frame.trackedAngles.Length == 0)
            {
                return false;
            }

            float perfectWindow = Mathf.Min(15f, angleToleranceDegrees * 0.5f);
            float effectiveTolerance = Mathf.Max(angleToleranceDegrees, perfectWindow + 0.001f);

            scoreBuffer.Clear();
            int lowScoreCount = 0;

            for (int i = 0; i < frame.trackedAngles.Length; i++)
            {
                PoseAngleSample sample = frame.trackedAngles[i];
                if (coreOnly && !IsCoreAngleSample(sample))
                {
                    continue;
                }

                int a = mirror ? MirrorLandmarkIndex(sample.A) : sample.A;
                int b = mirror ? MirrorLandmarkIndex(sample.B) : sample.B;
                int c = mirror ? MirrorLandmarkIndex(sample.C) : sample.C;

                if (!HasSufficientVisibility(liveVisibility, a) ||
                    !HasSufficientVisibility(liveVisibility, b) ||
                    !HasSufficientVisibility(liveVisibility, c))
                {
                    continue;
                }

                if (!TryCalculateJointAngle(liveLandmarks, a, b, c, out float liveAngle))
                {
                    continue;
                }

                float delta = Mathf.Abs(Mathf.DeltaAngle(liveAngle, sample.Angle));
                float score = ScoreAngleDelta(delta, perfectWindow, effectiveTolerance);
                scoreBuffer.Add(score);
                if (score < 0.35f)
                {
                    lowScoreCount++;
                }
            }

            if (scoreBuffer.Count < minimumRequiredSamples)
            {
                return false;
            }

            scoreBuffer.Sort();
            int dropCount = 0;
            if (scoreBuffer.Count >= 8)
            {
                dropCount = 2;
            }
            else if (scoreBuffer.Count >= 5)
            {
                dropCount = 1;
            }

            float baseConfidence = ComputeWeightedBaseScore(scoreBuffer, dropCount);
            float lowScoreRatio = lowScoreCount / (float)Mathf.Max(scoreBuffer.Count, 1);
            float mismatchPenalty = ComputeMismatchPenalty(lowScoreRatio, scoreBuffer.Count);
            confidence = Mathf.Clamp01(baseConfidence * mismatchPenalty);
            return true;
        }

        private bool TryCollectLandmarkSources(
            MotionFrameTemplate frame,
            Vector2[] liveLandmarks,
            float[] liveVisibility,
            bool mirror,
            bool coreOnly,
            int minimumRequiredSamples)
        {
            templateSourcePointBuffer.Clear();
            liveSourcePointBuffer.Clear();

            for (int i = 0; i < frame.trackedLandmarks.Length; i++)
            {
                PosePointSample point = frame.trackedLandmarks[i];
                if (coreOnly && !IsCoreLandmarkIndex(point.Index))
                {
                    continue;
                }

                int liveIndex = mirror ? MirrorLandmarkIndex(point.Index) : point.Index;
                if (!IsValidLandmarkIndex(liveIndex))
                {
                    continue;
                }

                if (!HasSufficientVisibility(liveVisibility, liveIndex))
                {
                    continue;
                }

                templateSourcePointBuffer.Add(point.Position);
                liveSourcePointBuffer.Add(liveLandmarks[liveIndex]);
            }

            return templateSourcePointBuffer.Count >= minimumRequiredSamples &&
                liveSourcePointBuffer.Count >= minimumRequiredSamples;
        }

