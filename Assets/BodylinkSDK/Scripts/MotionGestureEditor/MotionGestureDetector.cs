        private static PoseAngleSample[] FilterAngleSamplesByMotion(
            PoseAngleSample[] samples,
            HashSet<ulong> movingAngleKeys,
            Dictionary<ulong, float> angleMotionScores,
            int minimumRequired)
        {
            if (samples == null || samples.Length == 0)
            {
                return null;
            }

            bool[] include = new bool[samples.Length];
            int includeCount = 0;

            for (int i = 0; i < samples.Length; i++)
            {
                ulong key = CreateAngleKey(samples[i].A, samples[i].B, samples[i].C);
                if (movingAngleKeys != null && movingAngleKeys.Contains(key))
                {
                    include[i] = true;
                    includeCount++;
